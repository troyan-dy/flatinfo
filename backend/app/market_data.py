def _by_country_and_city(
    rows: Mapping[str, Mapping[str, _CityPrices]],
) -> dict[tuple[str, str], _CityPrices]:
    flat: dict[tuple[str, str], _CityPrices] = {}
    for code, cities in rows.items():
        for city, prices in cities.items():
            flat[code, city] = prices
    return flat


