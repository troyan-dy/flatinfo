"""Рыночные данные по странам и городам — оценки для расчёта.

Это БАЗА ОЦЕНОК, не онлайн-котировки: бесплатного глобального API с ценами на жильё
и арендой нет. Цифры — усреднённые рыночные ориентиры (центр/средний сегмент,
порядок величины), которые пользователь может скорректировать. Все цены — в местной
валюте страны.

Структура:
- COUNTRY: экономические параметры страны (ставка ипотеки, налог, рост цен и т.д.)
  плюс базовые цена/аренда за м² «среднего города» страны.
- CITY: уточнения цена/аренда за м² по конкретным городам (перекрывают COUNTRY).
- GLOBAL_FALLBACK: если страна неизвестна.
"""

