    property_tax_rate: float  # налог на недвижимость, % стоимости в год
    home_appreciation: float  # рост цен на жильё, годовых
    rent_growth: float  # рост аренды, годовых
    investment_return: float  # типичная доходность вложений, годовых
    buy_closing_pct: float  # издержки покупки, % цены
    sell_closing_pct: float  # издержки продажи, % цены


